import type { Exercise, Level, Program, ProgramDay, ProgramId } from '../lib/types'

type E = [name: string, reps: string, sets: number] | [name: string, reps: string, sets: number, kind: 'skills']

const ex = (list: E[]): Exercise[] =>
  list.map(([name, reps, sets, kind]) => (kind ? { name, reps, sets, kind } : { name, reps, sets }))

const day = (n: number, exercises: E[], focus?: string): ProgramDay => ({
  id: `d${n}`,
  label: `Dag ${n}`,
  ...(focus ? { focus } : {}),
  exercises: ex(exercises),
})

const level = (index: number, days: ProgramDay[]): Level => ({ index, name: `Level ${index}`, days })

